package xyz.busterbrown1218.more_wathe.role;

import dev.doctor4t.wathe.api.Role;
import dev.doctor4t.wathe.api.WatheRoles;
import dev.doctor4t.wathe.cca.GameWorldComponent;
import dev.doctor4t.wathe.client.gui.RoleAnnouncementTexts;
import dev.doctor4t.wathe.util.AnnounceWelcomePayload;
import net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.server.network.ServerPlayerEntity;
import org.agmas.harpymodloader.Harpymodloader;
import org.agmas.harpymodloader.events.ModdedRoleAssigned;
import pro.fazeclan.river.stupid_express.constants.SERoles;
import xyz.busterbrown1218.more_wathe.components.GuardianAngelPlayerComponent;
import xyz.busterbrown1218.more_wathe.config.ConfigFile;

public class GuardianRole {
    public static void resetRole(ServerPlayerEntity playerEntity) {
        GameWorldComponent gameWorldComponent = GameWorldComponent.KEY.get(playerEntity.getWorld());

        Role roleAfterFailure = WatheRoles.CIVILIAN;
        if (FabricLoader.getInstance().isModLoaded("stupid_express") && ConfigFile.HANDLER.instance().guardianDefaultsToAmnesiac) roleAfterFailure = SERoles.AMNESIAC;
        GuardianAngelPlayerComponent.KEY.get(playerEntity).reset();

        gameWorldComponent.addRole(playerEntity, roleAfterFailure);
        ModdedRoleAssigned.EVENT.invoker().assignModdedRole(playerEntity, roleAfterFailure);
        if (Harpymodloader.VANNILA_ROLES.contains(roleAfterFailure)) {
            ServerPlayNetworking.send(
                    playerEntity,
                    new AnnounceWelcomePayload(
                            RoleAnnouncementTexts.ROLE_ANNOUNCEMENT_TEXTS.indexOf(RoleAnnouncementTexts.CIVILIAN),
                            gameWorldComponent.getAllKillerTeamPlayers().size(),
                            0
                    )
            );
        } else {
            ServerPlayNetworking.send(
                    playerEntity,
                    new AnnounceWelcomePayload(
                            RoleAnnouncementTexts.ROLE_ANNOUNCEMENT_TEXTS.indexOf(Harpymodloader.autogeneratedAnnouncements.get(roleAfterFailure)),
                            gameWorldComponent.getAllKillerTeamPlayers().size(),
                            0
                    )
            );
        }
    }
}
